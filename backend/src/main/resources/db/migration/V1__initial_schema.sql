-- ResolveIQ I-ITSM - initial schema.
-- Portable SQL: runs unchanged on PostgreSQL (production) and H2 in PostgreSQL mode (development/tests).

-- ---------------------------------------------------------------------------------------------
-- Users: single-table inheritance (Employee, Technician, TeamLead, Administrator, ItManager)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_type             VARCHAR(31)  NOT NULL,
    full_name             VARCHAR(120) NOT NULL,
    email                 VARCHAR(160) NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,
    phone                 VARCHAR(30),
    department            VARCHAR(80),
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP WITH TIME ZONE,
    last_login_at         TIMESTAMP WITH TIME ZONE,
    -- technician-only columns (NULL for other user types)
    max_active_incidents  INTEGER,
    available             BOOLEAN,
    experience_level      VARCHAR(20),
    last_assigned_at      TIMESTAMP WITH TIME ZONE,
    team_lead_id          BIGINT,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_team_lead FOREIGN KEY (team_lead_id) REFERENCES users (id),
    CONSTRAINT ck_users_type CHECK (user_type IN ('EMPLOYEE', 'TECHNICIAN', 'TEAM_LEAD', 'ADMIN', 'MANAGER'))
);

CREATE TABLE technician_skills (
    technician_id BIGINT      NOT NULL,
    skill         VARCHAR(40) NOT NULL,
    CONSTRAINT pk_technician_skills PRIMARY KEY (technician_id, skill),
    CONSTRAINT fk_skills_technician FOREIGN KEY (technician_id) REFERENCES users (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------------------------
-- Service catalogue and its dependency graph
-- ---------------------------------------------------------------------------------------------
CREATE TABLE it_services (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    criticality VARCHAR(20)  NOT NULL,
    owner_team  VARCHAR(100),
    user_base   INTEGER      NOT NULL DEFAULT 0,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_services_code UNIQUE (code)
);

CREATE TABLE service_dependencies (
    service_id    BIGINT NOT NULL,
    depends_on_id BIGINT NOT NULL,
    CONSTRAINT pk_service_dependencies PRIMARY KEY (service_id, depends_on_id),
    CONSTRAINT fk_dep_service FOREIGN KEY (service_id) REFERENCES it_services (id) ON DELETE CASCADE,
    CONSTRAINT fk_dep_depends_on FOREIGN KEY (depends_on_id) REFERENCES it_services (id) ON DELETE CASCADE,
    CONSTRAINT ck_dep_no_self CHECK (service_id <> depends_on_id)
);

CREATE TABLE categories (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(40)   NOT NULL,
    name               VARCHAR(80)   NOT NULL,
    description        VARCHAR(300),
    keywords           VARCHAR(2000),
    security_sensitive BOOLEAN       NOT NULL DEFAULT FALSE,
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_categories_code UNIQUE (code)
);

-- ---------------------------------------------------------------------------------------------
-- SLA policies (service_id NULL = organisation-wide default for that priority)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE sla_policies (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      VARCHAR(100) NOT NULL,
    priority                  VARCHAR(5)   NOT NULL,
    service_id                BIGINT,
    response_minutes          INTEGER      NOT NULL,
    resolution_minutes        INTEGER      NOT NULL,
    warning_threshold_percent INTEGER      NOT NULL DEFAULT 75,
    active                    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    version                   BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_sla_service FOREIGN KEY (service_id) REFERENCES it_services (id) ON DELETE CASCADE,
    CONSTRAINT ck_sla_priority CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_sla_targets CHECK (response_minutes > 0 AND resolution_minutes >= response_minutes)
);

-- ---------------------------------------------------------------------------------------------
-- Incidents (aggregate root) with embedded SLA record, resolution and feedback
-- ---------------------------------------------------------------------------------------------
CREATE SEQUENCE incident_number_seq START WITH 1001 INCREMENT BY 1;

CREATE TABLE incidents (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number                    VARCHAR(20)   NOT NULL,
    title                     VARCHAR(160)  NOT NULL,
    description               VARCHAR(4000) NOT NULL,
    reporter_id               BIGINT        NOT NULL,
    category_id               BIGINT,
    auto_classified           BOOLEAN       NOT NULL DEFAULT FALSE,
    classification_confidence DOUBLE PRECISION,
    service_id                BIGINT        NOT NULL,
    impact                    VARCHAR(10)   NOT NULL,
    urgency                   VARCHAR(10)   NOT NULL,
    affected_users            INTEGER       NOT NULL,
    priority                  VARCHAR(5),
    priority_score            DOUBLE PRECISION,
    priority_rationale        VARCHAR(1000),
    priority_strategy         VARCHAR(60),
    status                    VARCHAR(20)   NOT NULL,
    assignee_id               BIGINT,
    assigned_at               TIMESTAMP WITH TIME ZONE,
    assignment_strategy       VARCHAR(60),
    -- SLA record
    sla_policy_name           VARCHAR(100),
    sla_response_minutes      INTEGER,
    sla_resolution_minutes    INTEGER,
    sla_warning_percent       INTEGER,
    sla_started_at            TIMESTAMP WITH TIME ZONE,
    sla_response_due_at       TIMESTAMP WITH TIME ZONE,
    sla_resolution_due_at     TIMESTAMP WITH TIME ZONE,
    sla_responded_at          TIMESTAMP WITH TIME ZONE,
    sla_resolved_at           TIMESTAMP WITH TIME ZONE,
    sla_response_breached     BOOLEAN       NOT NULL DEFAULT FALSE,
    sla_resolution_breached   BOOLEAN       NOT NULL DEFAULT FALSE,
    sla_warning_issued        BOOLEAN       NOT NULL DEFAULT FALSE,
    sla_paused_at             TIMESTAMP WITH TIME ZONE,
    sla_paused_seconds        BIGINT        NOT NULL DEFAULT 0,
    -- escalation
    escalation_level          VARCHAR(20)   NOT NULL DEFAULT 'NONE',
    escalated_at              TIMESTAMP WITH TIME ZONE,
    escalated_to_id           BIGINT,
    -- resolution & feedback
    resolution_summary        VARCHAR(2000),
    resolution_root_cause     VARCHAR(1000),
    resolved_by_id            BIGINT,
    feedback_rating           INTEGER,
    feedback_comment          VARCHAR(1000),
    feedback_submitted_at     TIMESTAMP WITH TIME ZONE,
    -- duplicates & closure
    duplicate_of_id           BIGINT,
    duplicate_score           DOUBLE PRECISION,
    duplicate_confirmed       BOOLEAN       NOT NULL DEFAULT FALSE,
    closed_at                 TIMESTAMP WITH TIME ZONE,
    closure_note              VARCHAR(1000),
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    version                   BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_incidents_number UNIQUE (number),
    CONSTRAINT fk_incidents_reporter FOREIGN KEY (reporter_id) REFERENCES users (id),
    CONSTRAINT fk_incidents_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_incidents_service FOREIGN KEY (service_id) REFERENCES it_services (id),
    CONSTRAINT fk_incidents_assignee FOREIGN KEY (assignee_id) REFERENCES users (id),
    CONSTRAINT fk_incidents_escalated_to FOREIGN KEY (escalated_to_id) REFERENCES users (id),
    CONSTRAINT fk_incidents_resolved_by FOREIGN KEY (resolved_by_id) REFERENCES users (id),
    CONSTRAINT fk_incidents_duplicate_of FOREIGN KEY (duplicate_of_id) REFERENCES incidents (id),
    CONSTRAINT ck_incidents_feedback CHECK (feedback_rating IS NULL OR (feedback_rating BETWEEN 1 AND 5)),
    CONSTRAINT ck_incidents_users CHECK (affected_users >= 1)
);

CREATE INDEX ix_incidents_status ON incidents (status);
CREATE INDEX ix_incidents_priority ON incidents (priority);
CREATE INDEX ix_incidents_assignee ON incidents (assignee_id);
CREATE INDEX ix_incidents_reporter ON incidents (reporter_id);
CREATE INDEX ix_incidents_service ON incidents (service_id);
CREATE INDEX ix_incidents_created ON incidents (created_at);

CREATE TABLE incident_notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT        NOT NULL,
    author_id   BIGINT,
    author_name VARCHAR(120)  NOT NULL,
    note_type   VARCHAR(20)   NOT NULL,
    internal    BOOLEAN       NOT NULL DEFAULT FALSE,
    content     VARCHAR(4000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_notes_incident FOREIGN KEY (incident_id) REFERENCES incidents (id) ON DELETE CASCADE,
    CONSTRAINT fk_notes_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE INDEX ix_notes_incident ON incident_notes (incident_id);

-- ---------------------------------------------------------------------------------------------
-- Audit trail (append-only) and notifications
-- ---------------------------------------------------------------------------------------------
CREATE TABLE audit_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id        BIGINT,
    actor_name      VARCHAR(120)  NOT NULL,
    actor_role      VARCHAR(30),
    action          VARCHAR(40)   NOT NULL,
    incident_id     BIGINT,
    incident_number VARCHAR(20),
    previous_state  VARCHAR(60),
    new_state       VARCHAR(60),
    description     VARCHAR(1000) NOT NULL
);

CREATE INDEX ix_audit_incident ON audit_records (incident_number);
CREATE INDEX ix_audit_time ON audit_records (occurred_at);

CREATE TABLE notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id    BIGINT        NOT NULL,
    channel         VARCHAR(10)   NOT NULL,
    event_type      VARCHAR(40),
    subject         VARCHAR(200)  NOT NULL,
    message         VARCHAR(2000) NOT NULL,
    incident_number VARCHAR(20),
    urgent          BOOLEAN       NOT NULL DEFAULT FALSE,
    delivery_status VARCHAR(12)   NOT NULL,
    is_read         BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    error_message   VARCHAR(500),
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_notifications_recipient ON notifications (recipient_id, channel, is_read);

CREATE TABLE system_settings (
    setting_key   VARCHAR(60)  PRIMARY KEY,
    setting_value VARCHAR(200) NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by    VARCHAR(120)
);
