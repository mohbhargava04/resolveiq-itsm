-- =============================================================================================
-- V4: "Report with assistant" conversations (chatbot-based incident reporting).
-- A session holds the step reached, the draft learnt so far and how it ended; messages are its
-- append-only transcript. Portable SQL (PostgreSQL and H2).
-- =============================================================================================
CREATE TABLE chat_sessions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT       NOT NULL,
    step                    VARCHAR(30)  NOT NULL,
    outcome                 VARCHAR(30)  NOT NULL,
    draft_title             VARCHAR(160),
    draft_description       VARCHAR(4000),
    draft_service_code      VARCHAR(40),
    draft_service_confirmed BOOLEAN      DEFAULT FALSE NOT NULL,
    draft_impact            VARCHAR(20),
    draft_urgency           VARCHAR(20),
    draft_device            VARCHAR(80),
    device_asked            BOOLEAN      DEFAULT FALSE NOT NULL,
    major_checked           BOOLEAN      DEFAULT FALSE NOT NULL,
    self_help_checked       BOOLEAN      DEFAULT FALSE NOT NULL,
    duplicates_checked      BOOLEAN      DEFAULT FALSE NOT NULL,
    duplicates_acknowledged BOOLEAN      DEFAULT FALSE NOT NULL,
    incident_number         VARCHAR(20),
    deflected_article_id    BIGINT,
    finished_at             TIMESTAMP WITH TIME ZONE,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    version                 BIGINT       DEFAULT 0 NOT NULL,
    CONSTRAINT fk_chat_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_chat_sessions_outcome CHECK (outcome IN
        ('OPEN', 'INCIDENT_CREATED', 'DEFLECTED', 'JOINED_MAJOR_INCIDENT', 'DUPLICATE_AVOIDED', 'CANCELLED'))
);
CREATE INDEX ix_chat_sessions_user ON chat_sessions (user_id, created_at);
CREATE INDEX ix_chat_sessions_outcome ON chat_sessions (outcome, created_at);

CREATE TABLE chat_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT        NOT NULL,
    line_no    INTEGER       NOT NULL,
    sender     VARCHAR(12)   NOT NULL,
    body       VARCHAR(4000) NOT NULL,
    sent_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_chat_messages_session FOREIGN KEY (session_id) REFERENCES chat_sessions (id) ON DELETE CASCADE,
    CONSTRAINT uk_chat_messages_position UNIQUE (session_id, line_no),
    CONSTRAINT ck_chat_messages_sender CHECK (sender IN ('USER', 'ASSISTANT'))
);
