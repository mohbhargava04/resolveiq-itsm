-- =============================================================================================
-- V2: security hardening (sessions, MFA, password reset, federated sign-in) and collaboration
--     features (attachments, knowledge base, major incidents, inbound e-mail).
-- Written in portable SQL that runs on both PostgreSQL and H2 (PostgreSQL mode).
-- =============================================================================================

-- ---------------------------------------------------------------------------------------------
-- Users: profile, federated identity, token versioning and two-factor authentication
-- ---------------------------------------------------------------------------------------------
ALTER TABLE users ADD COLUMN location VARCHAR(80);
ALTER TABLE users ADD COLUMN avatar_url VARCHAR(500);
ALTER TABLE users ADD COLUMN profile_completed BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE users ADD COLUMN password_enabled BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE users ADD COLUMN google_subject VARCHAR(64);
-- bumped on deactivation, role change, password change and "sign out everywhere": every access
-- token carries the version it was issued with, and older tokens are rejected immediately
ALTER TABLE users ADD COLUMN token_version INTEGER NOT NULL DEFAULT 0;
-- TOTP secret encrypted with AES-GCM (never stored in plain text)
ALTER TABLE users ADD COLUMN mfa_secret VARCHAR(200);
ALTER TABLE users ADD COLUMN mfa_pending_secret VARCHAR(200);
ALTER TABLE users ADD COLUMN mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN mfa_last_used_step BIGINT;
ALTER TABLE users ADD CONSTRAINT uk_users_google_subject UNIQUE (google_subject);

-- ---------------------------------------------------------------------------------------------
-- Refresh tokens (one row per issued token; a "family" is one signed-in device/browser)
-- Only a SHA-256 hash of the token is stored, so a database leak does not leak sessions.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    token_hash     VARCHAR(64)  NOT NULL,
    family_id      VARCHAR(36)  NOT NULL,
    family_started TIMESTAMP WITH TIME ZONE NOT NULL,
    issued_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    rotated_at     TIMESTAMP WITH TIME ZONE,
    revoked_at     TIMESTAMP WITH TIME ZONE,
    revoke_reason  VARCHAR(40),
    sign_in_method VARCHAR(20)  NOT NULL,
    user_agent     VARCHAR(250),
    ip_address     VARCHAR(45),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_refresh_family ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_user ON refresh_tokens (user_id);

-- ---------------------------------------------------------------------------------------------
-- Single-use tokens: password reset links (hashed, short-lived)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE one_time_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    purpose    VARCHAR(20) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_one_time_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_one_time_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- Two-factor recovery codes (hashed, each usable once)
CREATE TABLE mfa_recovery_codes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT      NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    used_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_recovery_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_recovery_user ON mfa_recovery_codes (user_id);

-- ---------------------------------------------------------------------------------------------
-- Attachments: metadata and content are separate tables so listing never loads file bytes
-- ---------------------------------------------------------------------------------------------
CREATE TABLE attachments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    BIGINT       NOT NULL,
    uploaded_by_id BIGINT,
    uploaded_by    VARCHAR(120) NOT NULL,
    file_name      VARCHAR(200) NOT NULL,
    content_type   VARCHAR(100) NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    sha256         VARCHAR(64)  NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_attachment_incident FOREIGN KEY (incident_id) REFERENCES incidents (id) ON DELETE CASCADE,
    CONSTRAINT fk_attachment_uploader FOREIGN KEY (uploaded_by_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_attachment_size CHECK (size_bytes > 0)
);

CREATE INDEX ix_attachment_incident ON attachments (incident_id);

CREATE TABLE attachment_contents (
    attachment_id BIGINT PRIMARY KEY,
    data          BYTEA NOT NULL,
    CONSTRAINT fk_content_attachment FOREIGN KEY (attachment_id) REFERENCES attachments (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------------------------
-- Knowledge base
-- ---------------------------------------------------------------------------------------------
CREATE TABLE kb_articles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(160)  NOT NULL,
    symptoms           VARCHAR(2000) NOT NULL,
    solution           VARCHAR(6000) NOT NULL,
    category_id        BIGINT,
    service_id         BIGINT,
    tags               VARCHAR(300),
    status             VARCHAR(12)   NOT NULL,
    audience           VARCHAR(12)   NOT NULL,
    source_incident_id BIGINT,
    author_id          BIGINT,
    author_name        VARCHAR(120)  NOT NULL,
    views              INTEGER       NOT NULL DEFAULT 0,
    helpful_votes      INTEGER       NOT NULL DEFAULT 0,
    unhelpful_votes    INTEGER       NOT NULL DEFAULT 0,
    deflections        INTEGER       NOT NULL DEFAULT 0,
    published_at       TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_kb_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE SET NULL,
    CONSTRAINT fk_kb_service FOREIGN KEY (service_id) REFERENCES it_services (id) ON DELETE SET NULL,
    CONSTRAINT fk_kb_source FOREIGN KEY (source_incident_id) REFERENCES incidents (id) ON DELETE SET NULL,
    CONSTRAINT fk_kb_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_kb_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT ck_kb_audience CHECK (audience IN ('EVERYONE', 'IT_STAFF'))
);

CREATE INDEX ix_kb_status ON kb_articles (status);

CREATE TABLE kb_votes (
    article_id BIGINT  NOT NULL,
    user_id    BIGINT  NOT NULL,
    helpful    BOOLEAN NOT NULL,
    voted_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_kb_votes PRIMARY KEY (article_id, user_id),
    CONSTRAINT fk_vote_article FOREIGN KEY (article_id) REFERENCES kb_articles (id) ON DELETE CASCADE,
    CONSTRAINT fk_vote_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------------------------
-- Major incidents: one incident is declared "major"; related incidents are linked to it and all
-- affected people receive its status updates
-- ---------------------------------------------------------------------------------------------
ALTER TABLE incidents ADD COLUMN major BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE incidents ADD COLUMN major_stage VARCHAR(20);
ALTER TABLE incidents ADD COLUMN major_declared_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE incidents ADD COLUMN major_parent_id BIGINT;
ALTER TABLE incidents ADD CONSTRAINT fk_incidents_major_parent FOREIGN KEY (major_parent_id) REFERENCES incidents (id);
CREATE INDEX ix_incidents_major_parent ON incidents (major_parent_id);

CREATE TABLE major_incident_updates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT        NOT NULL,
    stage       VARCHAR(20)   NOT NULL,
    message     VARCHAR(2000) NOT NULL,
    author_id   BIGINT,
    author_name VARCHAR(120)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_major_update_incident FOREIGN KEY (incident_id) REFERENCES incidents (id) ON DELETE CASCADE,
    CONSTRAINT fk_major_update_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_major_updates_incident ON major_incident_updates (incident_id);

-- ---------------------------------------------------------------------------------------------
-- Inbound e-mail log (replies to notifications, and new incidents sent by e-mail)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE inbound_emails (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    received_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    from_address    VARCHAR(160)  NOT NULL,
    subject         VARCHAR(200)  NOT NULL,
    body_excerpt    VARCHAR(1000),
    outcome         VARCHAR(30)   NOT NULL,
    incident_number VARCHAR(20),
    detail          VARCHAR(500)
);

CREATE INDEX ix_inbound_received ON inbound_emails (received_at);

-- Notifications keep the full body so the admin delivery log can show what was sent
ALTER TABLE notifications ALTER COLUMN message SET DATA TYPE VARCHAR(4000);
